#!/usr/bin/env bash
# Generates the demo's secrets on the VM, once: deploy/demo/.env and
# deploy/demo/secrets/identity-signing.pem. Neither is ever committed.
#
#   deploy/demo/secrets.sh                # API host from this VM's public IP
#   deploy/demo/secrets.sh api.example.in # or a name you own
#
# It refuses to run twice: rotating these keys would invalidate every session
# and every encrypted Identity field. Delete .env deliberately to start over.
set -euo pipefail
cd "$(dirname "$0")"

if [[ -e .env ]]; then
  echo "secrets.sh: .env already exists; refusing to overwrite it." >&2
  exit 1
fi

host="${1:-}"
if [[ -z "$host" ]]; then
  ip=$(curl -fsS https://api.ipify.org)
  host="api.${ip}.sslip.io"
fi

# 48+ random characters, letters and digits only (safe in connection strings and env files).
rand() { openssl rand -base64 64 | tr -dc 'A-Za-z0-9' | head -c "${1:-48}"; }

umask 077
cat > .env <<ENV
# Generated by secrets.sh on $(date -u +%Y-%m-%dT%H:%MZ). Keep private.
API_HOST=${host}
WEB_ORIGIN=https://khazana-online.netlify.app
WEB_RP_ID=khazana-online.netlify.app
POSTGRES_PASSWORD=$(rand 40)
RABBITMQ_PASSWORD=$(rand 40)
FIELD_KEY=$(rand 64)
REPORTING_INTERNAL_KEY=$(rand 64)
REPORTING_AUDIT_KEY=$(rand 64)
CATALOG_INTERNAL_KEY=$(rand 64)
CATALOG_SIGNING_SEED=$(openssl rand -base64 32)
ENV

# Identity's ES256 token-signing key (PKCS#8 PEM, P-256).
mkdir -p secrets
chmod 700 secrets
openssl ecparam -name prime256v1 -genkey -noout | openssl pkcs8 -topk8 -nocrypt -out secrets/identity-signing.pem
# Readable inside the container (non-root uid); the folder above stays private to this user.
chmod 644 secrets/identity-signing.pem

echo "Wrote deploy/demo/.env and secrets/identity-signing.pem. API host: https://${host}"
