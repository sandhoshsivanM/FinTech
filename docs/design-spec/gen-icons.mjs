#!/usr/bin/env node
/**
 * Bakes the Lucide icons the app actually uses into `src/icons.js`.
 *
 * The nav, the topbar and a dozen screens are keyed on specific Lucide glyphs.
 * Approximating them by hand would make the artboards subtly wrong in the one
 * place a reader is most likely to notice, so the geometry is lifted from the
 * same `lucide-react` package the app renders — no runtime dependency, just a
 * one-off codegen whose output is committed.
 *
 *   node docs/design-spec/gen-icons.mjs
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ICONS_DIR = join(HERE, '../../webapp/node_modules/lucide-react/dist/esm/icons');

/** Every glyph the document needs, by lucide kebab name. */
const WANTED = [
  // sidebar
  'layout-dashboard', 'line-chart', 'bar-chart-3', 'trending-up', 'table-2', 'star',
  'candlestick-chart', 'coins', 'landmark', 'wallet', 'receipt', 'calendar-days',
  'scale', 'pie-chart', 'repeat', 'flag', 'credit-card', 'shield', 'life-buoy',
  'gauge', 'upload', 'newspaper', 'bell', 'stethoscope', 'settings', 'circle-help',
  // chrome + actions
  'search', 'plus', 'lock', 'sun', 'moon', 'chevron-right', 'chevron-left', 'chevron-down',
  'panel-left-close', 'download', 'refresh-cw', 'eye', 'eye-off', 'user', 'check',
  'x', 'arrow-up-right', 'arrow-down-right', 'trending-down', 'circle-alert',
  'triangle-alert', 'circle-check', 'info', 'trash-2', 'pencil', 'filter', 'arrow-right',
  'shield-check', 'fingerprint-pattern', 'file-text', 'sparkles', 'clock', 'external-link',
  'building-2', 'car', 'heart-pulse', 'graduation-cap', 'plane', 'home', 'piggy-bank',
];

const out = {};
const missing = [];

/** Follow `export { default } from './other.mjs'` alias modules to the source. */
function readIcon(name, depth = 0) {
  const file = join(ICONS_DIR, `${name}.mjs`);
  if (!existsSync(file) || depth > 3) return null;
  const src = readFileSync(file, 'utf8');
  const alias = src.match(/export \{ default \} from '\.\/([\w-]+)\.mjs'/);
  if (alias) return readIcon(alias[1], depth + 1);
  const m = src.match(/const __iconNode = (\[[\s\S]*?\]);/);
  return m ? m[1] : null;
}

for (const name of WANTED) {
  const literal = readIcon(name);
  if (!literal) { missing.push(name); continue; }
  // The literal is plain JS data (arrays of [tag, attrs]); evaluating it here is
  // reading our own node_modules, at build time, into a codegen step.
  const nodes = new Function(`return ${literal}`)();
  out[name] = nodes.map(([tag, attrs]) => {
    const a = Object.entries(attrs)
      .filter(([k]) => k !== 'key')
      .map(([k, v]) => `${k}="${v}"`)
      .join(' ');
    return `<${tag} ${a}/>`;
  }).join('');
}

if (missing.length) console.warn(`missing: ${missing.join(', ')}`);

const js = `/**
 * Lucide icon geometry, generated by \`gen-icons.mjs\` from the exact
 * \`lucide-react\` build the web app renders. Do not hand-edit — re-run the
 * generator instead.
 *
 * Lucide is ISC licensed. Stroke conventions (24-unit box, 2px stroke, round
 * caps and joins) are carried through by \`icon()\` below.
 */
const NODES = ${JSON.stringify(out, null, 2)};

/** Render one glyph at \`size\`, inheriting \`currentColor\`. */
export function icon(name, size = 18, { stroke = 2, style = '' } = {}) {
  const d = NODES[name];
  if (!d) return '';
  return \`<svg width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none"
    stroke="currentColor" stroke-width="\${stroke}" stroke-linecap="round" stroke-linejoin="round"
    style="flex:none;display:block;\${style}">\${d}</svg>\`;
}

export const ICON_NAMES = Object.keys(NODES);
`;

writeFileSync(join(HERE, 'src/icons.js'), js);
console.log(`icons  ${Object.keys(out).length} glyphs -> src/icons.js`);
