"""Regenerates lib/core/help/section_help_data.dart from the web wording.
Usage: python3 tool/gen_section_help.py <section-help.json> <glossary.ts>"""
import json, re, sys
def q(s):
    return "'" + s.replace('\\','\\\\').replace("'","\\'").replace('$','\\$').replace('\n','\\n') + "'"
sec = json.load(open(sys.argv[1]))
ts = open(sys.argv[2]).read()
g = ts.split('export const GLOSSARY')[1].split('} as const')[0]
pat = re.compile(r'(\w+): \{\s*title: (?:\'((?:[^\'\\]|\\.)*)\'|"((?:[^"\\])*)"),\s*body: (?:\'((?:[^\'\\]|\\.)*)\'|"((?:[^"\\])*)"),\s*\}', re.S)
terms = []
for m in pat.finditer(g):
    t = m.group(2) if m.group(2) is not None else m.group(3)
    b = m.group(4) if m.group(4) is not None else m.group(5)
    terms.append((m.group(1), t.replace("\\'", "'"), b.replace("\\'", "'")))
out = ["// GENERATED by tool/gen_section_help.py from the web wording (SECTION_HELP",
       "// and GLOSSARY in webapp/src/lib). Do not edit by hand; change the web copy.",
       "", "import 'section_help.dart';", "",
       "const Map<String, HelpEntry> kWebSectionHelp = {"]
for e in sec:
    out.append(f"  {q(e['key'])}: HelpEntry({q(e['title'])}, {q(e['body'])}),")
out += ["};", "", "const Map<String, HelpEntry> kGlossary = {"]
for k,t,b in terms:
    out.append(f"  {q(k)}: HelpEntry({q(t)}, {q(b)}),")
out += ["};", ""]
open('lib/core/help/section_help_data.dart','w').write("\n".join(out))
print(len(sec), len(terms))
